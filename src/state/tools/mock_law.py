"""
src.state.tools.mock_law —— Mock 法条/案例检索工具（演示用，不用查真的 Milvus）

💡 为什么写 Mock 而不是真的赔偿金计算器？
    因为你秋招学习的是「记忆 + 编排系统」，工具的业务逻辑不影响对这两块的理解。
    这个 Mock 工具足以演示：
        FSM 状态如何触发 Tool 调用 → Orchestrator 调 ToolRegistry → Tool.run() → ToolResult 写回 Memory
    将来你要换成真实赔偿金计算器 / Word 生成器，只需同样继承 BaseTool + register 即可
"""
from .base import BaseTool


class MockLawLookUpTool(BaseTool):
    """
    演示用 Mock 法条检索工具：输入「案由关键词」→ 返回 3-5 条硬编码的法条片段
    （完全不访问真实数据库，保证 Demo 离线可跑）
    """
    name = "law_lookup"
    description = ("输入一个劳动纠纷的案由关键词（如 '违法解除','未签合同','加班费'），"
                   "返回相关的劳动合同法核心法条原文和适用要点。")
    input_schema = {
        "required": ["keyword"],
        "properties": {
            "keyword": {
                "type": "string",
                "description": "案由关键词，例如：辞退、未签合同、拖欠工资、加班费、年假",
            }
        },
    }

    KNOWLEDGE_BASE = {
        "辞退": [
            ("劳动合同法第47条", "经济补偿按劳动者在本单位工作的年限，每满一年支付一个月工资的标准向劳动者支付。六个月以上不满一年的，按一年计算；不满六个月的，向劳动者支付半个月工资的经济补偿。"),
            ("劳动合同法第48条", "用人单位违反本法规定解除或者终止劳动合同，劳动者要求继续履行劳动合同的，用人单位应当继续履行；劳动者不要求继续履行劳动合同或者劳动合同已经不能继续履行的，用人单位应当依照本法第八十七条规定支付赔偿金。"),
            ("劳动合同法第87条", "用人单位违反本法规定解除或者终止劳动合同的，应当依照本法第四十七条规定的经济补偿标准的二倍向劳动者支付赔偿金。"),
        ],
        "违法解除": [
            ("劳动合同法第47条", "经济补偿计算规则：N=工龄×月薪，月薪高于社平3倍时按3倍封顶且最多12年。"),
            ("劳动合同法第87条", "违法解除赔偿金 = 2 × N。注意：2N 和 N+1（代通知金）不可同时主张。"),
            ("劳动合同法第40条", "只有『医疗期满/不胜任工作/客观情况重大变化』三种情况提前30天通知或额外付1个月工资（+1），其他合法解除不需要 +1。"),
        ],
        "未签合同": [
            ("劳动合同法第82条第1款", "用人单位自用工之日起超过一个月不满一年未与劳动者订立书面劳动合同的，应当向劳动者每月支付二倍的工资。二倍工资最多支持 11 个月。"),
            ("劳动合同法第14条第3款", "用工满一年不签书面合同 → 视为已订立无固定期限劳动合同。"),
        ],
        "加班费": [
            ("劳动法第44条", "平日加班 150% 工资；休息日加班 200% 工资（不能安排补休时）；法定节假日加班 300% 工资（不得以补休替代）。"),
        ],
        "年假": [
            ("职工带薪年休假条例第3条", "工作满1年不满10年：5天/年；满10年不满20年：10天/年；满20年：15天/年。"),
            ("企业职工带薪年休假实施办法第10条", "未休年假工资报酬 = 日工资收入 × 未休天数 × 200%（100% 正常工资已发）。"),
        ],
        "拖欠工资": [
            ("劳动合同法第85条", "未及时足额支付工资 → 由劳动行政部门责令限期支付；逾期不付 → 按应付金额 50%-100% 加付赔偿金。"),
            ("劳部发[1994]481号第3条", "克扣/无故拖欠工资 → 还需加发相当于工资报酬 25% 的经济补偿金。"),
        ],
    }

    # 关键词同义词映射（用户输入模糊时兜底）
    KEYWORD_ALIAS = {
        "辞职": "辞退", "离职": "辞退", "开除": "辞退", "解雇": "辞退", "裁员": "辞退",
        "双倍工资": "未签合同", "二倍工资": "未签合同", "没签合同": "未签合同",
        "加班": "加班费", "加班工资": "加班费",
        "工资拖欠": "拖欠工资", "欠薪": "拖欠工资", "克扣工资": "拖欠工资",
        "年休假": "年假",
    }

    def _run(self, params: dict) -> dict:
        kw_raw = params.get("keyword", "").strip()
        if not kw_raw:
            return {"keyword": kw_raw, "articles": [], "notice": "关键词为空"}
        kw = kw_raw
        # 同义词归一化
        for alias, canonical in self.KEYWORD_ALIAS.items():
            if alias in kw:
                kw = canonical
                break
        # 模糊匹配：知识库的 key 出现在用户输入里就命中
        matched = []
        for key in self.KNOWLEDGE_BASE:
            if key in kw or kw in key:
                matched.extend(self.KNOWLEDGE_BASE[key])
        # 兜底：没命中就用辞退默认
        if not matched:
            matched = self.KNOWLEDGE_BASE["辞退"]
        return {
            "keyword_raw": kw_raw,
            "keyword_normalized": kw,
            "articles": [
                {"name": name, "text": text} for name, text in matched[:6]
            ],
            "notice": f"命中 {len(matched)} 条法条规则（Mock 数据，演示用）",
        }