# ============================================================
# 构建完整分析用的 User Message
# ============================================================
def build_analysis_prompt(user_input: str, laws_text: str, cases_text: str = "") -> str:
    """
    构建发送给 LLM 的完整 Prompt

    Args:
        user_input: 用户的原始描述
        laws_text:   检索到的法律法规条文（来自 laws 库）
        cases_text:  检索到的相似案例/裁判文书/法规解读（来自 non_laws 库）

    Returns:
        完整的 user message 内容
    """
    cases_section = f"## 检索到的相似案例（含裁判文书、法规解读）\n\n{cases_text}" \
        if cases_text and cases_text.strip() else \
        "## 检索到的相似案例（含裁判文书、法规解读）\n\n（未检索到有效的相似案例数据）"

    prompt = f"""## 用户咨询

{user_input}

## 检索到的法律法规依据

{laws_text}

---

{cases_section}

---

请你按照以下8个模块，逐一输出分析结果（使用 Markdown 格式）：

### 输出顺序
1. {MODULE_SUMMARY}
2. {MODULE_COMPENSATION}
3. {MODULE_LEGAL_BASIS}
4. {MODULE_CASES}
5. {MODULE_EVIDENCE}
6. {MODULE_ACTION_PLAN}
7. {MODULE_RISK}
8. {MODULE_CONCLUSION}

请确保：
- 「法律依据」模块只引用「检索到的法律法规依据」中的条文；「相似案例参考」模块只引用「检索到的相似案例」中的材料
- 所有法条和案例都来自检索结果，不要编造
- 遇到不确定的地方，如实标注
- 使用通俗语言但保持专业
- 输出完整，不要省略任何模块
"""
    return prompt